// Service Helpers
export function getAllServices() {
  try {
    const saved = localStorage.getItem(STORAGE_SERVICES_KEY)
    if (saved) {
      const parsed = JSON.parse(saved)
      if (Array.isArray(parsed) && parsed.length > 0) return parsed
    }
  } catch (e) {
    console.error('Failed to load services from localStorage', e)
  }
  return DEFAULT_SERVICES
}

export function saveAllServices(services) {
  try {
    localStorage.setItem(STORAGE_SERVICES_KEY, JSON.stringify(services))
  } catch (e) {
    console.error('Failed to save services to localStorage', e)
  }
}

export function resetToDefaultServices() {
  localStorage.setItem(STORAGE_SERVICES_KEY, JSON.stringify(DEFAULT_SERVICES))
  return DEFAULT_SERVICES
}

export function getBookedServiceVouchers() {
  try {
    const saved = localStorage.getItem(STORAGE_BOOKINGS_KEY)
    if (saved) {
      return JSON.parse(saved)
    }
  } catch (e) {
    console.error('Failed to load vouchers', e)
  }
  return []
}
